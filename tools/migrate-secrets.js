const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const CONFIG_PATH = path.join(ROOT, 'config.json');
const WEB_CONFIG_PATH = path.join(ROOT, 'web', 'config.json');
const ENV_PATH = path.join(ROOT, '.env');

function readJsonSafe(p) {
	try { return JSON.parse(fs.readFileSync(p, 'utf8')); } catch { return null; }
}

const cfg = readJsonSafe(CONFIG_PATH) || {};
const webCfg = readJsonSafe(WEB_CONFIG_PATH) || {};

const mappings = [
	['JWT_SECRET',                   webCfg.jwtSecret  || cfg.jwtSecret],
	['ADMIN_PASSWORD',               cfg.adminPassword],
	['RCON_PASSWORD',                cfg.server && cfg.server.password],
	['STEAM_API_KEY',                cfg.steamApiKey],
	['DISCORD_WEBHOOK_URL',          cfg.webhookUrl],
	['DISCORD_BACKUP_WEBHOOK_URL',   cfg.backupWebhookUrl],
	['DISCORD_CLIENT_ID',            cfg.discord && cfg.discord.clientId],
	['DISCORD_CLIENT_SECRET',        cfg.discord && cfg.discord.clientSecret],
	['CS2_SERVER_IP',                cfg.server && cfg.server.ip],
	['CS2_SERVER_PORT',              cfg.server && cfg.server.port],
	['HITL_INTERNAL_TOKEN',          cfg.hitlInternalToken],
];

const existingEnv = {};
if (fs.existsSync(ENV_PATH)) {
	const txt = fs.readFileSync(ENV_PATH, 'utf8');
	for (const line of txt.split('\n')) {
		const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
		if (m) existingEnv[m[1]] = m[2];
	}
}

const lines = [
	'# Auto-generated by tools/migrate-secrets.js — gözden geçir + production\'da chmod 600',
	'# Generated at: ' + new Date().toISOString(),
	'',
];
let migrated = 0;
let skipped = 0;
let alreadyHad = 0;

for (const [name, value] of mappings) {
	if (existingEnv[name] && existingEnv[name].trim()) {
		lines.push(`${name}=${existingEnv[name]}`);
		alreadyHad++;
	} else if (value !== undefined && value !== null && value !== '') {
		const quoted = /[\s"'$#\\]/.test(String(value)) ? `"${String(value).replace(/"/g, '\\"')}"` : String(value);
		lines.push(`${name}=${quoted}`);
		migrated++;
	} else {
		lines.push(`${name}=`);
		skipped++;
	}
}

fs.writeFileSync(ENV_PATH, lines.join('\n') + '\n', 'utf8');

console.log('');
console.log('=================================================');
console.log('  Secrets Migration Tamamlandı');
console.log('=================================================');
console.log(`  → .env yazıldı: ${ENV_PATH}`);
console.log(`  ✓ ${migrated} secret config.json'dan migrate edildi`);
console.log(`  ↺ ${alreadyHad} secret zaten .env'de mevcuttu`);
console.log(`  ⚠ ${skipped} secret config.json'da yok (boş atandı)`);
console.log('');
console.log('  Sonraki adımlar:');
console.log('   1) cat .env  (gözden geçir, eksikleri doldur)');
console.log('   2) Windows: dosya ACL\'ı sadece Administrator için okuma izni');
console.log('   3) service.js restart — process.env.X olarak erişilebilir');
console.log('   4) Code refactor: config.adminPassword → process.env.ADMIN_PASSWORD');
console.log('      (kademeli yapılabilir — ikisi de çalışır arada)');
console.log('');
